impl Translation {
    pub fn status_summary(&self, count: usize) -> String {
        match self.app_title {
            "Q Note" if self.language_toggle == "en" => format!("共 {count} 条"),
            _ => format!("Total {count}"),
        }
    }

    pub fn update_available_title(&self, version: &str) -> String {
        if self.language_toggle == "en" {
            format!("检测到新版本： {version}")
        } else {
            format!("New version available: {version}")
        }
    }
}

